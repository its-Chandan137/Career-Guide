const LangContext = createContext<{ lang: Lang, setLang: (l:Lang)=>void, t:(k:string)=>string }|null>(null)

export function LangProvider({ children }:{ children: ReactNode }){
  const [lang, setLangState] = useState<Lang>(()=>{
    const s = localStorage.getItem('komal_lang')
    return (s==='hi' || s==='en') ? s : 'en'
  })
  useEffect(()=>{
    localStorage.setItem('komal_lang', lang)
    document.documentElement.lang = lang
  },[lang])
  const setLang = (l:Lang)=> setLangState(l)
  const t = (k:string)=> dict[lang][k] ?? dict.en[k] ?? k
  return <LangContext.Provider value={{lang, setLang, t}}>{children}</LangContext.Provider>
}

export function useLang(){
  const c = useContext(LangContext)
  if(!c) throw new Error('LangProvider missing')
  return c
}
